fn largest_miss_km(reference: &Reference) -> f64 {
    let mut largest = 0.0;
    for (k, want) in reference.positions.iter().enumerate() {
        let jd = 2411545.0 + 4000.0 * k as f64;
        let got = (reference.position)(&TDB::from_julian_date(JulianDate::new(jd, 0.0))).unwrap();
        let miss = (got - Vector3::from_array(*want)).magnitude() * AU_KM;
        largest = libm::fmax(largest, miss);
    }
    largest
}

#[test]
fn truncated_tables_stay_near_the_full_series() {
    for reference in &REFERENCES {
        let miss = largest_miss_km(reference);
        assert!(miss < reference.bound_km, "{}: {} km", reference.name, miss);
    }
}
